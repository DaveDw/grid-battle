"""Manyworlds set 2: water, living growth and spores, native pixel geometry."""
from build_set2 import pen

CARDS = [
    ("wave_rider", "Wave Rider", "A purple surfboard riding a compact teal curl."),
    ("brine_splash", "Brine Splash", "A sideways brine splash driving a purple push arrow."),
    ("thornvine", "Thornvine", "A hooked green vine armed with large purple thorns."),
    ("sap_poultice", "Sap Poultice", "A folded green medicinal leaf secured by a purple wrap."),
    ("maelstrom", "Maelstrom", "A low spiralling teal whirlpool drawing in a purple mote."),
    ("pollen_cloud", "Pollen Cloud", "An open green pollen pod scattering large purple grains."),
    ("barnacle_shell", "Barnacle Shell", "A purple spiral shell with growing teal barnacles."),
    ("tsunami", "Tsunami", "A tall teal breaker curling over a purple undertow."),
    ("overgrowth", "Overgrowth", "A purple spore seed erupting into a spreading tangle of green roots."),
    ("worldshaper", "Worldshaper", "A cupped green hand reshaping a small land-and-water world."),
]


def draw(name):
    p = pen("manyworlds")
    if name == "wave_rider":
        p.poly([(3, 28), (7, 24), (8, 18), (12, 13), (17, 11), (23, 12), (26, 15), (26, 19), (23, 21), (20, 20), (19, 17), (22, 17), (22, 15), (18, 14), (14, 17), (14, 22), (18, 25), (24, 27), (28, 28)], "t")
        p.line([(7, 24), (8, 18), (12, 13), (17, 11), (23, 12), (25, 15)], "h")
        p.line([(18, 15), (15, 18), (15, 22), (18, 25), (24, 27)], "s")
        p.poly([(6, 9), (10, 9), (22, 3), (26, 3), (24, 7), (11, 13), (7, 12)], "p")
        p.line([(7, 9), (10, 9), (22, 3), (25, 3)], "ph")
        p.line([(8, 12), (11, 13), (24, 7)], "ps")
    elif name == "brine_splash":
        p.poly([(3, 13), (7, 14), (7, 6), (10, 9), (12, 14), (16, 10), (17, 14), (15, 18), (20, 19), (20, 24), (11, 27), (6, 24), (6, 19), (3, 17)], "t")
        p.line([(7, 6), (10, 10), (11, 15), (8, 17)], "h")
        p.line([(6, 21), (9, 24), (14, 25), (19, 23)], "s", 2)
        p.poly([(19, 10), (24, 10), (24, 6), (29, 13), (24, 20), (24, 16), (20, 16)], "p")
        p.line([(20, 10), (24, 10), (24, 7)], "ph"); p.line([(25, 17), (28, 13)], "ps")
        p.ell((3, 4, 5, 7), "h")
    elif name == "thornvine":
        p.line([(9, 28), (9, 23), (21, 19), (23, 14), (20, 8), (12, 7), (8, 11), (9, 15), (13, 16)], "s", 5)
        p.line([(8, 27), (8, 23), (20, 18), (21, 14), (19, 9), (12, 9), (10, 12), (11, 14)], "t", 3)
        p.line([(8, 24), (20, 19)], "h"); p.line([(9, 11), (12, 8), (18, 8)], "h")
        for points in ([(14, 8), (17, 8), (15, 2)], [(21, 12), (23, 15), (28, 10)], [(18, 20), (21, 21), (23, 26)], [(8, 22), (10, 24), (3, 25)]):
            p.poly(points, "p"); p.line(points[:2], "ps"); p.px([points[2]], "ph")
    elif name == "sap_poultice":
        p.poly([(5, 7), (17, 4), (24, 8), (27, 18), (22, 26), (11, 28), (5, 21)], "t")
        p.poly([(24, 9), (27, 18), (22, 26), (11, 28), (8, 25), (19, 23), (22, 18)], "s")
        p.line([(5, 7), (17, 4), (23, 8)], "h"); p.line([(6, 8), (6, 19)], "h")
        p.line([(9, 11), (20, 22)], "h"); p.line([(14, 16), (15, 9)], "s")
        p.poly([(6, 19), (21, 7), (24, 11), (9, 24)], "p")
        p.line([(6, 19), (21, 7)], "ph"); p.line([(9, 24), (24, 11)], "ps")
        p.poly([(13, 16), (16, 13), (19, 16), (16, 19)], "ph")
        p.px([(16, 16)], "ps")
    elif name == "maelstrom":
        p.line([(4, 13), (7, 8), (15, 5), (24, 7), (28, 12), (28, 19), (22, 25), (12, 27), (5, 23), (3, 19), (7, 14), (14, 11), (21, 12), (23, 16), (19, 20), (13, 21), (10, 18), (14, 15), (18, 16)], "t", 3)
        p.line([(4, 13), (7, 8), (15, 5), (22, 7)], "h")
        p.line([(28, 16), (28, 19), (22, 25), (12, 27), (5, 23)], "s")
        p.line([(7, 14), (14, 11), (21, 12)], "h")
        p.line([(20, 20), (14, 21), (11, 19)], "s")
        p.poly([(17, 15), (20, 17), (17, 19), (15, 17)], "p"); p.px([(17, 15)], "ph")
    elif name == "pollen_cloud":
        p.line([(8, 28), (10, 21), (14, 16)], "s", 3)
        p.line([(8, 27), (10, 22)], "h")
        p.poly([(10, 23), (5, 21), (3, 14), (8, 16), (10, 19), (12, 12), (16, 9), (17, 16), (14, 22)], "t")
        p.line([(3, 14), (8, 17)], "h"); p.line([(12, 15), (16, 10)], "h")
        p.line([(16, 17), (14, 22), (11, 23)], "s")
        for x, y, r in ((8, 5, 2), (20, 5, 3), (25, 14, 3), (21, 23, 2)):
            p.poly([(x - r, y - 1), (x - 1, y - r), (x + r - 1, y - r), (x + r, y), (x + 1, y + r), (x - r, y + r - 1)], "p")
            p.px([(x - r + 1, y - 1), (x - 1, y - r)], "ph")
            p.line([(x, y + r), (x + r, y)], "ps")
    elif name == "barnacle_shell":
        p.poly([(6, 4), (13, 5), (16, 9), (23, 9), (28, 15), (28, 22), (23, 27), (14, 28), (7, 24), (3, 18), (4, 10)], "p")
        p.line([(6, 4), (12, 5), (15, 9)], "ph")
        p.line([(4, 11), (3, 18), (7, 24), (14, 28), (23, 27), (28, 22)], "ps", 2)
        p.line([(9, 8), (10, 14), (14, 20), (21, 22), (24, 19), (23, 15), (18, 13), (15, 15), (18, 18), (20, 17)], "ps", 2)
        p.line([(11, 12), (14, 18), (21, 20), (22, 18)], "ph")
        for x, y in ((5, 18), (11, 24), (25, 23)):
            p.poly([(x - 2, y + 2), (x - 1, y - 2), (x + 2, y - 2), (x + 3, y + 2)], "t")
            p.line([(x - 1, y - 2), (x + 1, y - 2)], "h"); p.px([(x + 1, y), (x + 2, y + 2)], "s")
    elif name == "tsunami":
        p.poly([(3, 27), (3, 17), (6, 12), (11, 8), (17, 7), (23, 8), (28, 11), (29, 15), (27, 18), (24, 18), (22, 15), (23, 13), (20, 12), (17, 13), (16, 16), (18, 20), (23, 23), (29, 24), (29, 28), (3, 28)], "t")
        p.line([(3, 18), (6, 12), (11, 8), (17, 7), (23, 8), (28, 11)], "h", 2)
        p.line([(23, 13), (20, 12), (17, 13), (16, 16), (18, 20), (23, 23)], "s")
        p.poly([(24, 9), (28, 11), (29, 15), (27, 18), (25, 18), (26, 14), (24, 12)], "h")
        p.line([(5, 24), (7, 18), (10, 16)], "h")
        p.poly([(3, 27), (9, 25), (15, 26), (22, 27), (29, 27), (29, 29), (3, 29)], "p")
        p.line([(3, 27), (9, 25), (15, 26)], "ph"); p.line([(4, 29), (28, 29)], "ps")
    elif name == "overgrowth":
        p.line([(16, 13), (16, 23)], "s", 4)
        for pts in ([(16, 18), (10, 18), (7, 15), (4, 15)], [(16, 21), (11, 23), (11, 28), (7, 28)], [(16, 23), (20, 25), (24, 25), (27, 28)], [(17, 17), (22, 18), (25, 15), (28, 15)], [(16, 24), (16, 29)]):
            p.line(pts, "s", 3); p.line(pts, "t")
        p.poly([(10, 20), (4, 21), (3, 25), (9, 24)], "t"); p.line([(4, 21), (8, 21)], "h")
        p.poly([(21, 20), (27, 21), (29, 24), (23, 24)], "t"); p.line([(22, 20), (27, 21)], "h")
        p.poly([(16, 3), (22, 7), (23, 11), (19, 16), (12, 16), (8, 11), (10, 7)], "p")
        p.line([(10, 7), (16, 3), (21, 7)], "ph")
        p.line([(22, 10), (19, 15), (13, 15)], "ps", 2)
        p.line([(15, 7), (13, 10)], "ph")
    elif name == "worldshaper":
        p.ell((9, 2, 27, 20), "t")
        p.arc((9, 2, 27, 20), 180, 280, "h")
        p.arc((9, 2, 27, 20), 0, 100, "s", 2)
        p.poly([(13, 5), (17, 4), (18, 7), (16, 9), (17, 12), (13, 13), (11, 10)], "m")
        p.line([(13, 5), (16, 4)], "mh"); p.line([(13, 12), (16, 11)], "ms")
        p.poly([(23, 12), (25, 14), (23, 17), (19, 18), (19, 15)], "m")
        p.px([(22, 13), (23, 13)], "mh"); p.line([(20, 17), (22, 17)], "ms")
        p.poly([(3, 15), (5, 15), (8, 22), (13, 24), (22, 24), (26, 21), (29, 21), (28, 25), (23, 28), (10, 29), (5, 25)], "t")
        p.line([(3, 15), (5, 16), (8, 23), (13, 25), (23, 25)], "h")
        p.line([(6, 25), (10, 29), (23, 28), (28, 25)], "s")
    else:
        raise ValueError(name)
    return p.finish()
